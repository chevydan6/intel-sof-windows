// Exact, single output-only GPIO resource captured from PUJJOTEEN firmware.
// Refuse different firmware layouts rather than guessing a pin to drive.
#pragma once

static int
SofAmpMatchesResource(const unsigned char *bytes, unsigned long length)
{
    static const unsigned char expected[] = {
        0x8c,0x25,0x00,0x01,0x01,0x01,0x00,0x02,0x00,0x00,0x00,
        0x00,0x00,0x00,0x17,0x00,0x00,0x19,0x00,0x28,0x00,0x00,
        0x00,0x4b,0x00,0x5c,0x5f,0x53,0x42,0x2e,0x50,0x43,0x49,
        0x30,0x2e,0x47,0x50,0x49,0x4f,0x00,0x79,0x00
    };
    unsigned long i;
    if (bytes == 0 || length != sizeof(expected)) return 0;
    for (i = 0; i < sizeof(expected); ++i)
        if (bytes[i] != expected[i]) return 0;
    return 1;
}
