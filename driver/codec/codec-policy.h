// Captured PUJJOTEEN _CRS: I2C3 address 0x1a, 400 kHz; GPIO interrupt 87.
// Do not perform even the I2C-mode selection on another resource map.
static __inline int CodecMatchesResource(const unsigned char *data, unsigned long size)
{
    static const unsigned char expected[] = {
        0x8e,0x1e,0x00,0x01,0x00,0x01,0x02,0x00,0x00,0x01,0x06,0x00,
        0x80,0x1a,0x06,0x00,0x1a,0x00,0x5c,0x5f,0x53,0x42,0x2e,0x50,
        0x43,0x49,0x30,0x2e,0x49,0x32,0x43,0x33,0x00,0x8c,0x25,0x00,
        0x01,0x00,0x01,0x00,0x05,0x00,0x00,0x00,0x00,0x00,0x00,0x17,
        0x00,0x00,0x19,0x00,0x28,0x00,0x00,0x00,0x57,0x00,0x5c,0x5f,
        0x53,0x42,0x2e,0x50,0x43,0x49,0x30,0x2e,0x47,0x50,0x49,0x4f,
        0x00,0x79,0x00,
    };
    unsigned long i;
    if (!data || size != sizeof(expected)) return 0;
    for (i = 0; i < size; ++i) if (data[i] != expected[i]) return 0;
    return 1;
}
